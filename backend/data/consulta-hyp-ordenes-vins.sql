/*
  HyP · Órdenes + VINs únicos del mes
  Pegar en SSMS → base GMOFARRIL → Ejecutar (F5)

  Cambiar @mes / @anio para otro periodo.
  Julio 2026 esperado: 201 VINs únicos.
*/

USE GMOFARRIL;
GO

DECLARE @anio INT = 2026;
DECLARE @mes  INT = 7;

-- Una fila por VIN único (con orden(es) del mes)
SELECT
  UPPER(LTRIM(RTRIM(o.ORE_NUMSERIE))) AS vin,
  MIN(LTRIM(RTRIM(v.VTE_REFERENCIA1))) AS orden_ejemplo,
  STUFF((
    SELECT DISTINCT ', ' + LTRIM(RTRIM(v2.VTE_REFERENCIA1))
    FROM CON_MOVDET012026 m2
    INNER JOIN CON_POL012026 p2
      ON p2.POL_TIPO = m2.MOV_TIPOPOL
      AND p2.POL_CONSECUTIVO = m2.MOV_CONSPOL
      AND p2.POL_MES = m2.MOV_MES
    INNER JOIN ADE_VTAFI v2
      ON v2.VTE_DOCTO = LTRIM(RTRIM(p2.POL_REFERENCIA1))
    INNER JOIN SER_ORDEN o2
      ON LTRIM(RTRIM(v2.VTE_REFERENCIA1)) = LTRIM(RTRIM(o2.ORE_IDORDEN))
    WHERE m2.MOV_MES = @mes
      AND m2.MOV_TIPOPOL IN ('VS', 'DVS')
      AND (
        LTRIM(RTRIM(m2.MOV_NUMCTA)) LIKE '0470-0001%'
        OR LTRIM(RTRIM(m2.MOV_NUMCTA)) LIKE '0476-0001%'
        OR LTRIM(RTRIM(m2.MOV_NUMCTA)) LIKE '0477-0001%'
        OR LTRIM(RTRIM(m2.MOV_NUMCTA)) LIKE '0479-0001%'
      )
      AND UPPER(LTRIM(RTRIM(o2.ORE_NUMSERIE))) = UPPER(LTRIM(RTRIM(o.ORE_NUMSERIE)))
    FOR XML PATH(''), TYPE
  ).value('.', 'NVARCHAR(MAX)'), 1, 2, '') AS ordenes_mes,
  COUNT(DISTINCT LTRIM(RTRIM(v.VTE_REFERENCIA1))) AS num_ordenes,
  COUNT(DISTINCT LTRIM(RTRIM(p.POL_REFERENCIA1))) AS num_doctos,
  MIN(o.ORE_FECHACIE) AS cierre
FROM CON_MOVDET012026 m
INNER JOIN CON_POL012026 p
  ON p.POL_TIPO = m.MOV_TIPOPOL
  AND p.POL_CONSECUTIVO = m.MOV_CONSPOL
  AND p.POL_MES = m.MOV_MES
INNER JOIN ADE_VTAFI v
  ON v.VTE_DOCTO = LTRIM(RTRIM(p.POL_REFERENCIA1))
INNER JOIN SER_ORDEN o
  ON LTRIM(RTRIM(v.VTE_REFERENCIA1)) = LTRIM(RTRIM(o.ORE_IDORDEN))
WHERE m.MOV_MES = @mes
  AND m.MOV_TIPOPOL IN ('VS', 'DVS')
  AND (
    LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0470-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0476-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0477-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0479-0001%'
  )
  AND o.ORE_NUMSERIE IS NOT NULL
  AND LTRIM(RTRIM(o.ORE_NUMSERIE)) <> ''
GROUP BY UPPER(LTRIM(RTRIM(o.ORE_NUMSERIE))), o.ORE_NUMSERIE
ORDER BY vin;


-- Conteo rápido
SELECT COUNT(*) AS vins_unicos
FROM (
  SELECT DISTINCT UPPER(LTRIM(RTRIM(o.ORE_NUMSERIE))) AS vin
  FROM CON_MOVDET012026 m
  INNER JOIN CON_POL012026 p
    ON p.POL_TIPO = m.MOV_TIPOPOL
    AND p.POL_CONSECUTIVO = m.MOV_CONSPOL
    AND p.POL_MES = m.MOV_MES
  INNER JOIN ADE_VTAFI v
    ON v.VTE_DOCTO = LTRIM(RTRIM(p.POL_REFERENCIA1))
  INNER JOIN SER_ORDEN o
    ON LTRIM(RTRIM(v.VTE_REFERENCIA1)) = LTRIM(RTRIM(o.ORE_IDORDEN))
  WHERE m.MOV_MES = @mes
    AND m.MOV_TIPOPOL IN ('VS', 'DVS')
    AND (
      LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0470-0001%'
      OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0476-0001%'
      OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0477-0001%'
      OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0479-0001%'
    )
    AND o.ORE_NUMSERIE IS NOT NULL
    AND LTRIM(RTRIM(o.ORE_NUMSERIE)) <> ''
) x;


-- Detalle: una fila por orden + docto + VIN (sin agrupar)
SELECT DISTINCT
  LTRIM(RTRIM(v.VTE_REFERENCIA1)) AS orden,
  LTRIM(RTRIM(p.POL_REFERENCIA1)) AS docto,
  UPPER(LTRIM(RTRIM(o.ORE_NUMSERIE))) AS vin,
  o.ORE_FECHACIE AS cierre,
  LEFT(LTRIM(RTRIM(v.VTE_REFERENCIA1)), 1) AS letra
FROM CON_MOVDET012026 m
INNER JOIN CON_POL012026 p
  ON p.POL_TIPO = m.MOV_TIPOPOL
  AND p.POL_CONSECUTIVO = m.MOV_CONSPOL
  AND p.POL_MES = m.MOV_MES
INNER JOIN ADE_VTAFI v
  ON v.VTE_DOCTO = LTRIM(RTRIM(p.POL_REFERENCIA1))
INNER JOIN SER_ORDEN o
  ON LTRIM(RTRIM(v.VTE_REFERENCIA1)) = LTRIM(RTRIM(o.ORE_IDORDEN))
WHERE m.MOV_MES = @mes
  AND m.MOV_TIPOPOL IN ('VS', 'DVS')
  AND (
    LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0470-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0476-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0477-0001%'
    OR LTRIM(RTRIM(m.MOV_NUMCTA)) LIKE '0479-0001%'
  )
  AND o.ORE_NUMSERIE IS NOT NULL
  AND LTRIM(RTRIM(o.ORE_NUMSERIE)) <> ''
ORDER BY vin, orden, docto;
