#!/usr/bin/env node
'use strict';
/**
 * Copia la base del CRM (backend/data/crm-ciclos.db) al PostgreSQL de la oficina.
 *
 * - La estructura se lee del propio archivo SQLite (lo que crearon los ETL), así
 *   que no hay que mantener dos definiciones de tablas.
 * - Cada tabla se carga en <tabla>__nuevo y se intercambia en una sola
 *   transacción: quien consulte durante la carga sigue viendo los datos
 *   anteriores, nunca la tabla vacía o a medias.
 * - Antes de intercambiar se verifica: mismo número de filas y misma suma por
 *   columna numérica. Si algo no cuadra, la tabla anterior se queda intacta.
 *
 * Uso:
 *   node backend/scripts/migrar-crm-a-postgres.js                 (todas las tablas)
 *   node backend/scripts/migrar-crm-a-postgres.js --tablas crm_leads,crm_csi_ventas
 *   node backend/scripts/migrar-crm-a-postgres.js --sqlite /ruta/crm-ciclos.db
 *
 * Requiere CRM_PG_URL en backend/.env.
 */
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '../.env') });
const fs = require('fs');
const Database = require('better-sqlite3');
const { Client } = require('pg');

const MAX_PARAMS = 60000; // PostgreSQL acepta hasta 65535 parámetros por sentencia

function parseArgs(argv) {
  const out = { tablas: null, sqlite: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--tablas') out.tablas = String(argv[i + 1] || '').split(',').map((s) => s.trim()).filter(Boolean);
    if (argv[i] === '--sqlite') out.sqlite = argv[i + 1];
  }
  return out;
}

const qi = (name) => `"${String(name).replace(/"/g, '""')}"`;

/** Tipo de PostgreSQL equivalente a la afinidad de SQLite. */
function pgType(sqliteType) {
  const t = String(sqliteType || '').toUpperCase();
  if (t.includes('INT')) return 'bigint';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB') || t.includes('NUM') || t.includes('DEC')) return 'double precision';
  return 'text';
}

function describeTable(db, table) {
  const cols = db.prepare(`PRAGMA table_info(${qi(table)})`).all().map((c) => ({
    name: c.name,
    sqliteType: c.type,
    type: pgType(c.type),
    notnull: !!c.notnull,
    dflt: c.dflt_value,
    pk: c.pk,
  }));
  const indexes = db.prepare(
    "SELECT name, sql FROM sqlite_master WHERE type = 'index' AND tbl_name = ? AND sql IS NOT NULL",
  ).all(table).map((ix) => {
    const m = /CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?\S+\s+ON\s+\S+\s*\(([^)]+)\)/i.exec(ix.sql);
    return m ? { name: ix.name, unique: !!m[1], columns: m[2].split(',').map((s) => s.trim().replace(/^["`[]|["`\]]$/g, '')) } : null;
  }).filter(Boolean);
  return { cols, indexes };
}

function columnDdl(c, pkCols) {
  const single = pkCols.length === 1 && c.pk;
  if (single && c.type === 'bigint') return `${qi(c.name)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
  let ddl = `${qi(c.name)} ${c.type}`;
  if (single) ddl += ' PRIMARY KEY';
  if (c.notnull && !single) ddl += ' NOT NULL';
  if (c.dflt != null && /^'.*'$|^-?\d+(\.\d+)?$/.test(c.dflt)) ddl += ` DEFAULT ${c.dflt}`;
  return ddl;
}

/**
 * SQLite permite texto en columnas numéricas. PostgreSQL no.
 * - Texto que ya es un número limpio (" 15 ", "1200.5") se guarda como número.
 * - Lo demás ("$1,200", "N/A") queda NULL y se cuenta en el reporte.
 * No se «limpia» "$1,200" a 1200 a propósito: los servicios lo leían como 0 y
 * limpiarlo aquí movería cifras que ya se usan. Corregirlo es decisión aparte (ETL).
 */
function coerce(value, type, stats = {}, col = '') {
  if (value === null || value === undefined) return null;
  if (type === 'text') return typeof value === 'string' ? value : String(value);
  if (typeof value === 'number') return type === 'bigint' ? Math.trunc(value) : value;
  if (typeof value === 'bigint') return Number(value);
  const s = String(value).trim();
  if (s === '') return null;
  const n = Number(s);
  if (Number.isFinite(n)) {
    if (stats.convertidos) stats.convertidos[col] = (stats.convertidos[col] || 0) + 1;
    return type === 'bigint' ? Math.trunc(n) : n;
  }
  if (stats.raros) stats.raros[col] = (stats.raros[col] || 0) + 1;
  return null;
}

async function migrarTabla(db, pg, table) {
  const { cols, indexes } = describeTable(db, table);
  const pkCols = cols.filter((c) => c.pk).sort((a, b) => a.pk - b.pk);
  const nuevo = `${table}__nuevo`;
  const numeric = cols.filter((c) => c.type !== 'text');
  const raros = {};
  const convertidos = {};
  const sumas = Object.fromEntries(numeric.map((c) => [c.name, 0]));
  const stats = { raros, convertidos };

  await pg.query(`DROP TABLE IF EXISTS ${qi(nuevo)}`);
  const pkTabla = pkCols.length > 1 ? `, PRIMARY KEY (${pkCols.map((c) => qi(c.name)).join(', ')})` : '';
  await pg.query(`CREATE TABLE ${qi(nuevo)} (${cols.map((c) => columnDdl(c, pkCols)).join(', ')}${pkTabla})`);

  const names = cols.map((c) => c.name);
  const porLote = Math.max(1, Math.floor(MAX_PARAMS / names.length));
  const insertCols = names.map(qi).join(', ');
  const overriding = pkCols.length === 1 && pkCols[0].type === 'bigint' ? ' OVERRIDING SYSTEM VALUE' : '';
  let lote = [];
  let filas = 0;

  const flush = async () => {
    if (!lote.length) return;
    const params = [];
    const tuples = lote.map((row) => `(${names.map((n, j) => {
      const v = coerce(row[n], cols[j].type, stats, n);
      if (v !== null && n in sumas) sumas[n] += v;
      params.push(v);
      return `$${params.length}`;
    }).join(', ')})`);
    await pg.query(`INSERT INTO ${qi(nuevo)} (${insertCols})${overriding} VALUES ${tuples.join(', ')}`, params);
    filas += lote.length;
    lote = [];
  };

  for (const row of db.prepare(`SELECT * FROM ${qi(table)}`).iterate()) {
    lote.push(row);
    if (lote.length >= porLote) await flush(); // eslint-disable-line no-await-in-loop
  }
  await flush();

  // ── Verificación antes de intercambiar ──
  const origen = db.prepare(`SELECT COUNT(*) AS n FROM ${qi(table)}`).get().n;
  const { rows: [{ n: destino }] } = await pg.query(`SELECT COUNT(*)::bigint AS n FROM ${qi(nuevo)}`);
  const problemas = [];
  if (Number(destino) !== origen) problemas.push(`filas: SQLite ${origen} vs PostgreSQL ${destino}`);
  // Suma de lo enviado (ya convertido) contra lo que quedó guardado.
  for (const c of numeric) {
    const esperado = sumas[c.name];
    const { rows: [{ s: sd }] } = await pg.query(`SELECT COALESCE(SUM(${qi(c.name)}), 0)::double precision AS s FROM ${qi(nuevo)}`); // eslint-disable-line no-await-in-loop
    const tol = Math.max(0.01, Math.abs(esperado) * 1e-9);
    if (Math.abs(Number(sd) - esperado) > tol) problemas.push(`suma ${c.name}: esperado ${esperado} vs ${sd}`);
  }
  if (problemas.length) {
    await pg.query(`DROP TABLE IF EXISTS ${qi(nuevo)}`);
    return { table, ok: false, filas, problemas, raros, convertidos };
  }

  // Índices con nombre temporal; se renombran al intercambiar.
  for (const ix of indexes) {
    const cols2 = ix.columns.filter((c) => names.includes(c));
    if (!cols2.length) continue;
    await pg.query(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${qi(`${ix.name}__n`)} ON ${qi(nuevo)} (${cols2.map(qi).join(', ')})`); // eslint-disable-line no-await-in-loop
  }

  // ── Intercambio atómico ──
  await pg.query('BEGIN');
  try {
    await pg.query(`DROP TABLE IF EXISTS ${qi(table)}`);
    await pg.query(`ALTER TABLE ${qi(nuevo)} RENAME TO ${qi(table)}`);
    for (const ix of indexes) {
      await pg.query(`ALTER INDEX IF EXISTS ${qi(`${ix.name}__n`)} RENAME TO ${qi(ix.name)}`); // eslint-disable-line no-await-in-loop
    }
    if (overriding) {
      await pg.query(`SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX(${qi(pkCols[0].name)}) FROM ${qi(table)}), 0) + 1, false)`, [table, pkCols[0].name]);
    }
    await pg.query(
      `INSERT INTO crm_migracion_log (tabla, filas, columnas_con_texto_en_numero, migrado_en)
       VALUES ($1, $2, $3, now())
       ON CONFLICT (tabla) DO UPDATE SET filas = EXCLUDED.filas,
         columnas_con_texto_en_numero = EXCLUDED.columnas_con_texto_en_numero, migrado_en = now()`,
      [table, filas, JSON.stringify(raros)],
    );
    await pg.query('COMMIT');
  } catch (err) {
    await pg.query('ROLLBACK');
    throw err;
  }
  return { table, ok: true, filas, problemas: [], raros, convertidos };
}

/**
 * Migra todas las tablas (o las indicadas). La usa este script y la
 * sincronización programada del CRM cuando CRM_DB=postgres.
 */
async function migrarTodo({ sqlitePath, pgUrl, tablas = null, log = console.log } = {}) {
  sqlitePath = sqlitePath || process.env.CRM_SQLITE_PATH || path.join(__dirname, '../data/crm-ciclos.db');
  pgUrl = pgUrl || process.env.CRM_PG_URL;
  if (!fs.existsSync(sqlitePath)) throw new Error(`No existe la base SQLite: ${sqlitePath}`);
  if (!pgUrl) throw new Error('Falta CRM_PG_URL en backend/.env');

  const db = new Database(sqlitePath, { readonly: true, fileMustExist: true });
  const pg = new Client({
    connectionString: pgUrl,
    ssl: process.env.CRM_PG_SSL === 'true' ? { rejectUnauthorized: false } : false,
  });
  await pg.connect();
  const resultados = [];
  try {
    await pg.query(`CREATE TABLE IF NOT EXISTS crm_migracion_log (
      tabla text PRIMARY KEY, filas bigint, columnas_con_texto_en_numero jsonb, migrado_en timestamptz)`);
    const todas = db.prepare(
      "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    ).all().map((r) => r.name);
    const elegidas = tablas ? todas.filter((t) => tablas.includes(t)) : todas;
    const faltan = (tablas || []).filter((t) => !todas.includes(t));
    if (faltan.length && log) log(`No están en SQLite: ${faltan.join(', ')}`);

    for (const t of elegidas) {
      const t0 = Date.now();
      const r = await migrarTabla(db, pg, t); // eslint-disable-line no-await-in-loop
      r.segundos = ((Date.now() - t0) / 1000).toFixed(1);
      resultados.push(r);
      if (!log) continue;
      const raros = Object.entries(r.raros).map(([c, n]) => `${c}: ${n}`).join(', ');
      const conv = Object.entries(r.convertidos).map(([c, n]) => `${c}: ${n}`).join(', ');
      log(`${r.ok ? 'OK   ' : 'FALLA'} ${t.padEnd(24)} ${String(r.filas).padStart(9)} filas  ${r.segundos}s`
        + `${conv ? `\n      texto convertido a número: ${conv}` : ''}`
        + `${raros ? `\n      texto no numérico → NULL: ${raros}` : ''}`
        + `${r.problemas.length ? `\n      no cuadra: ${r.problemas.join('; ')}` : ''}`);
    }
  } finally {
    db.close();
    await pg.end();
  }
  return { ok: resultados.every((r) => r.ok), tablas: resultados };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const r = await migrarTodo({ sqlitePath: args.sqlite, tablas: args.tablas });
  if (!r.ok) process.exitCode = 1;
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}

module.exports = { migrarTodo, migrarTabla, describeTable, pgType, coerce };
